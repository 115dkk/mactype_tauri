import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "shared", "unity-anticheat-catalog.json");
const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const checkOnly = process.argv.includes("--check");

if (source.schema !== 1) throw new Error("Unsupported Unity anti-cheat catalog schema");

function validateList(name, values) {
  if (!Array.isArray(values) || values.length === 0) throw new Error(`${name} must be a non-empty array`);
  const unique = new Set();
  for (const value of values) {
    if (typeof value !== "string" || !value || value !== value.toLowerCase() || /[\\/]/u.test(value)) {
      throw new Error(`${name} contains a non-canonical top-level name: ${String(value)}`);
    }
    if (unique.has(value)) throw new Error(`${name} contains a duplicate: ${value}`);
    unique.add(value);
  }
  return [...unique].sort();
}

const exact = validateList("topLevelExact", source.topLevelExact);
const prefixes = validateList("topLevelPrefixes", source.topLevelPrefixes);
const cppValues = (values) => values.map((value) => `\tL${JSON.stringify(value)},`).join("\n");
const rustValues = (values) => values.map((value) => `    ${JSON.stringify(value)},`).join("\n");

const cpp = `// Generated by scripts/generate-unity-anticheat-catalog.mjs. Do not edit.\n#pragma once\n\nnamespace renderer { namespace unity {\nstatic const wchar_t* const kAntiCheatTopLevelExact[] = {\n${cppValues(exact)}\n};\nstatic const wchar_t* const kAntiCheatTopLevelPrefixes[] = {\n${cppValues(prefixes)}\n};\n}} // namespace renderer::unity\n`;

const rust = `// Generated by scripts/generate-unity-anticheat-catalog.mjs. Do not edit.\npub const ANTI_CHEAT_TOP_LEVEL_EXACT: &[&str] = &[\n${rustValues(exact)}\n];\npub const ANTI_CHEAT_TOP_LEVEL_PREFIXES: &[&str] = &[\n${rustValues(prefixes)}\n];\n`;

const outputs = [
  [path.join(root, "renderer", "generated_unity_anticheat_catalog.h"), cpp],
  [path.join(root, "service-runtime", "host", "src", "generated_unity_anticheat_catalog.rs"), rust],
];
for (const [output, content] of outputs) {
  if (checkOnly) {
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== content) {
      throw new Error(`Generated Unity anti-cheat catalog is stale: ${path.relative(root, output)}`);
    }
  } else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, content);
  }
}
